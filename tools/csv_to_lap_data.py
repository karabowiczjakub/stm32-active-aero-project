#!/usr/bin/env python3
"""Validate video telemetry and generate the STM32 Flash table; never edit CSV."""

import argparse
import csv
import hashlib
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COLUMNS = (
    "t_ms", "speed_kmh", "g_lateral_est", "g_longitudinal_est",
    "a_lateral_mps2_est", "a_longitudinal_mps2_est", "speed_quality", "g_quality",
)


def number(value):
    result = Decimal(value)
    if not result.is_finite():
        raise ValueError("non-finite number")
    return result


def generate(csv_path):
    samples = []
    with csv_path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != list(COLUMNS):
            raise ValueError("unexpected CSV columns")
        for line, row in enumerate(reader, 2):
            try:
                if None in row or any(value is None for value in row.values()):
                    raise ValueError("wrong column count")
                time = number(row["t_ms"])
                if time != len(samples) * 20 or time > 0xFFFFFFFF:
                    raise ValueError("timestamps must start at 0 and increase by 20 ms")
                speed = number(row["speed_kmh"])
                if speed != speed.to_integral_value() or not 0 <= speed <= 255:
                    raise ValueError("speed must be an integer in 0..255 km/h")
                g_values = [number(row[key]) for key in COLUMNS[2:4]]
                mg_values = [int((g * 1000).to_integral_value(rounding=ROUND_HALF_UP))
                             for g in g_values]
                if any(not -32768 <= mg <= 32767 for mg in mg_values):
                    raise ValueError("acceleration does not fit signed milli-g")
                for g, key in zip(g_values, COLUMNS[4:6]):
                    if abs(g * Decimal("9.80665") - number(row[key])) > Decimal("0.02"):
                        raise ValueError("inconsistent g and m/s2 columns")
                quality = {"read": 0, "interpolated": 1}[row["speed_quality"]]
                quality |= {"read": 0, "extended_roi": 2}[row["g_quality"]]
                samples.append((int(time), *mg_values, int(speed), quality))
            except (InvalidOperation, ValueError, KeyError) as error:
                raise ValueError(f"CSV line {line}: {error}") from error
    if len(samples) < 2:
        raise ValueError("at least two samples required")

    digest = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    notice = f"/* Generated by tools/csv_to_lap_data.py; CSV SHA256: {digest} */\n"
    header = notice + f"""#ifndef LAP_DATA_H_
#define LAP_DATA_H_

#include "app_config.h"

#if APP_LAP_SIM_ENABLED
#include <stdint.h>

#define LAP_DATA_COUNT {len(samples)}U
#define LAP_DATA_END_MS {samples[-1][0]}U
#define LAP_DATA_PERIOD_MS 20U
#define LAP_QUALITY_SPEED_INTERPOLATED 1U
#define LAP_QUALITY_G_EXTENDED_ROI 2U

/* Video coordinates: lateral +right, longitudinal +down; not raw IMU axes.
 * Acceleration is rounded to milli-g, without clipping to +/-2 g. */
typedef struct
{{
    uint32_t t_ms;
    int16_t lateral_mg;
    int16_t longitudinal_mg;
    uint8_t speed_kmh;
    uint8_t quality;
}} LapData_Sample_t;

extern const LapData_Sample_t lap_data[LAP_DATA_COUNT];
#endif
#endif
"""
    source = notice + """#include "lap_data.h"

#if APP_LAP_SIM_ENABLED
_Static_assert(sizeof(LapData_Sample_t) == 12U, "unexpected lap sample padding");

const LapData_Sample_t lap_data[LAP_DATA_COUNT] = {
"""
    source += "".join(f"    {{{t}U, {lat}, {lon}, {speed}U, {quality}U}},\n"
                      for t, lat, lon, speed, quality in samples)
    source += "};\n#endif\n"
    return {"Core/Inc/lap_data.h": header, "Core/Src/lap_data.c": source}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", nargs="?", type=Path, default=ROOT / "data/telemetry_50hz.csv")
    parser.add_argument("--output-root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    try:
        files = generate(args.csv)
        for relative, contents in files.items():
            path = args.output_root / relative
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != contents:
                    raise ValueError(f"stale generated file: {path}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(contents, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    print("PASS: lap data matches CSV" if args.check else "Generated lap_data.c/.h")


if __name__ == "__main__":
    main()
